import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_sched_virtual_call_scale.v"

# Every class overrides a suspendable virtual task, and a process calls it N_CLASSES times, so
# each call site may call N_CLASSES functions
N_CLASSES = 1000
# Share of verilation time spent in V3Delayed and V3SchedTiming (about 0.04 when linear,
# 0.6 when quadratic)
MAX_SHARE = 0.15
# Ignore a high share of a short time, e.g. from a load spike (quadratic takes several seconds)
MIN_SECONDS = 0.5


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_sched_virtual_call_scale.py\n")
        fh.write("class Base;\n")
        fh.write("  virtual task body();\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        for i in range(n):
            fh.write(f"class C{i} extends Base;\n")
            fh.write("  virtual task body();\n")
            fh.write("    #1;\n")
            fh.write("  endtask\n")
            fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    Base b;\n")
        for i in range(n):
            fh.write(f"    begin automatic C{i} c = new; b = c; b.body(); end\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename, N_CLASSES)

test.compile(verilator_flags2=["--timing", "--stats", "--no-debug-check"],
             make_main=False,
             verilator_make_gmake=False)

with open(test.stats, 'r', encoding="utf8") as fh:
    stats = fh.read()
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
stages = re.findall(r'Stage, Elapsed time \(sec\), \d+_(?:delayed|sched-gather)\s+(\S+)', stats)
if not total or len(stages) != 2:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = sum(float(t) for t in stages)
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3Delayed and V3SchedTiming took {share:.0%} of verilation time with " +
               f"{N_CLASSES} classes (over {MAX_SHARE:.0%})")

test.passes()
